"""SCIP for Python: run scip-python over a repo, decode the index it writes, and name what it links.

The index is protobuf. indy reads only the fields its field-number constants name, so it
decodes the wire format itself rather than take on the `protobuf` runtime and a module
generated by one protoc version. https://github.com/sourcegraph/scip/blob/main/scip.proto is
the schema.
"""

import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
from collections.abc import Iterator
from dataclasses import dataclass
from dataclasses import field
from pathlib import Path

from indy.chunker import extract_spans
from indy.config import SCIP_PYTHON_DIR
from indy.config import compact_path

# package-lock.json here pins scip-python and every package it pulls in. `npx pkg@version`
# pins only the first, and resolves the rest from caret ranges on each new machine.
LOCKFILE_DIR = Path(__file__).parent / 'scip_python'
LOCKFILES = ('package.json', 'package-lock.json')

# Symbols embed the project version. Pinned, so a symbol string survives a commit, and a
# directory that is not a git repo does not crash the run.
PROJECT_VERSION = '0'

SCIP_PYTHON_TIMEOUT_SECONDS = 1800

# Prints what scip-python's own pip-based lookup would produce, for the interpreter running it.
# A uv venv has no pip, and without this file the run aborts and leaves an empty index.
ENVIRONMENT_SCRIPT = """
import importlib.metadata, json, sys
out = []
for dist in importlib.metadata.distributions():
    files = [str(f) for f in (dist.files or []) if not str(f).startswith('..') and '__pycache__' not in str(f)]
    out.append({'name': dist.name, 'version': dist.version, 'files': [f for f in files if f.endswith(('.py', '.pyi'))]})
json.dump(out, sys.stdout)
"""

ROLE_DEFINITION = 0x1
ROLE_IMPORT = 0x2
ROLE_WRITE = 0x4

# Field numbers from scip.proto.
INDEX_DOCUMENTS = 2
DOCUMENT_RELATIVE_PATH = 1
DOCUMENT_OCCURRENCES = 2
DOCUMENT_SYMBOLS = 3
OCCURRENCE_RANGE = 1
OCCURRENCE_SYMBOL = 2
OCCURRENCE_ROLES = 3
SYMBOL_INFORMATION_SYMBOL = 1
SYMBOL_INFORMATION_RELATIONSHIPS = 4
RELATIONSHIP_SYMBOL = 1
RELATIONSHIP_FLAGS = {2: 'reference', 3: 'implementation', 4: 'type_definition', 5: 'definition'}

WIRE_VARINT = 0
WIRE_FIXED64 = 1
WIRE_LENGTH = 2
WIRE_FIXED32 = 5


class ScipError(Exception):
    """scip-python could not produce an index, or wrote one that cannot be read."""


@dataclass(frozen=True)
class Occurrence:
    """One place a symbol appears. Lines and columns are 0-based, as SCIP writes them."""

    line: int
    column: int
    end_line: int
    end_column: int
    symbol: str
    roles: int


@dataclass
class Document:
    relative_path: str
    occurrences: list[Occurrence] = field(default_factory=list)
    relationships: list[tuple[str, str, str]] = field(default_factory=list)  # (symbol, kind, target symbol)


def read_varint(data: bytes, at: int) -> tuple[int, int]:
    value = shift = 0
    while True:
        byte = data[at]
        at += 1
        value |= (byte & 0x7F) << shift
        shift += 7
        if not byte & 0x80:
            return value, at


def read_fields(data: bytes) -> Iterator[tuple[int, int | bytes]]:
    """Each (field number, value) of one message. A length-delimited value is its raw bytes."""
    at, end = 0, len(data)
    while at < end:
        key, at = read_varint(data, at)
        number, wire_type = key >> 3, key & 7
        if wire_type == WIRE_VARINT:
            value, at = read_varint(data, at)
            yield number, value
        elif wire_type == WIRE_LENGTH:
            length, at = read_varint(data, at)
            yield number, data[at : at + length]
            at += length
        elif wire_type == WIRE_FIXED64:
            yield number, data[at : at + 8]
            at += 8
        elif wire_type == WIRE_FIXED32:
            yield number, data[at : at + 4]
            at += 4
        else:
            raise ScipError(f'unsupported protobuf wire type {wire_type}')
    if at != end:
        raise ScipError('truncated protobuf message')


def read_packed_ints(value: int | bytes) -> list[int]:
    if isinstance(value, int):
        return [value]
    numbers, at = [], 0
    while at < len(value):
        number, at = read_varint(value, at)
        numbers.append(number)
    return numbers


def decode_occurrence(data: bytes) -> Occurrence | None:
    span: list[int] = []
    symbol, roles = '', 0
    for number, value in read_fields(data):
        if number == OCCURRENCE_RANGE:
            span += read_packed_ints(value)
        elif number == OCCURRENCE_SYMBOL and isinstance(value, bytes):
            symbol = value.decode()
        elif number == OCCURRENCE_ROLES and isinstance(value, int):
            roles = value
    if len(span) == 3:
        return Occurrence(span[0], span[1], span[0], span[2], symbol, roles)
    if len(span) == 4:
        return Occurrence(span[0], span[1], span[2], span[3], symbol, roles)
    return None


def decode_relationships(data: bytes) -> list[tuple[str, str, str]]:
    """A SymbolInformation's relationships, one row per flag each one sets."""
    symbol = ''
    found = []
    for number, value in read_fields(data):
        if number == SYMBOL_INFORMATION_SYMBOL and isinstance(value, bytes):
            symbol = value.decode()
        elif number == SYMBOL_INFORMATION_RELATIONSHIPS and isinstance(value, bytes):
            target, kinds = '', []
            for relation_number, relation_value in read_fields(value):
                if relation_number == RELATIONSHIP_SYMBOL and isinstance(relation_value, bytes):
                    target = relation_value.decode()
                elif relation_number in RELATIONSHIP_FLAGS and relation_value:
                    kinds.append(RELATIONSHIP_FLAGS[relation_number])
            found += [(kind, target) for kind in kinds]
    return [(symbol, kind, target) for kind, target in found]


def decode_document(data: bytes) -> Document:
    document = Document('')
    for number, value in read_fields(data):
        if not isinstance(value, bytes):
            continue
        if number == DOCUMENT_RELATIVE_PATH:
            document.relative_path = value.decode()
        elif number == DOCUMENT_OCCURRENCES:
            occurrence = decode_occurrence(value)
            if occurrence is not None:
                document.occurrences.append(occurrence)
        elif number == DOCUMENT_SYMBOLS:
            document.relationships += decode_relationships(value)
    return document


def decode_index(data: bytes) -> list[Document]:
    """Every document of a SCIP index. External symbols are skipped: indy links only what the repo defines."""
    try:
        return [decode_document(value) for number, value in read_fields(data) if number == INDEX_DOCUMENTS and isinstance(value, bytes)]
    except (IndexError, UnicodeDecodeError) as exc:
        raise ScipError(f'unreadable SCIP index: {exc}') from exc


IDENTIFIER_CHARACTERS = frozenset('_+-$abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789')


@dataclass(frozen=True)
class Descriptor:
    name: str
    suffix: str  # '/' namespace, '#' type, '.' term, '()' method, '[]' type parameter, '(arg)' parameter, ':' meta, '!' macro


def read_identifier(text: str, at: int) -> tuple[str, int]:
    if at < len(text) and text[at] == '`':
        name, at = '', at + 1
        while at < len(text):
            if text[at] == '`':
                if text[at + 1 : at + 2] == '`':
                    name, at = name + '`', at + 2
                    continue
                return name, at + 1
            name, at = name + text[at], at + 1
        return name, at
    start = at
    while at < len(text) and text[at] in IDENTIFIER_CHARACTERS:
        at += 1
    return text[start:at], at


def parse_descriptors(text: str) -> list[Descriptor]:
    """The descriptor chain of a symbol's last field, `` `pkg.mod`/Class#method(). ``."""
    descriptors, at = [], 0
    while at < len(text):
        if text[at] == '[':
            name, at = read_identifier(text, at + 1)
            descriptors.append(Descriptor(name, '[]'))
            at += 1
            continue
        if text[at] == '(':
            name, at = read_identifier(text, at + 1)
            descriptors.append(Descriptor(name, '(arg)'))
            at += 1
            continue
        name, at = read_identifier(text, at)
        if at >= len(text):
            break
        if text[at] == '(':
            close = text.find(').', at)
            if close == -1:
                break
            descriptors.append(Descriptor(name, '()'))
            at = close + 2
            continue
        descriptors.append(Descriptor(name, text[at]))
        at += 1
    return descriptors


@dataclass(frozen=True)
class SymbolName:
    """A SCIP symbol as indy prints one: the module it lives in, and its dotted name inside it."""

    module: str
    name: str
    kind: str  # 'class', 'function', 'method' or 'variable'

    @property
    def member(self) -> str:
        return self.name.rpartition('.')[2]


def name_symbol(symbol: str) -> SymbolName | None:
    """`… `pkg.registry`/Provider#install_all().` as module `pkg.registry`, name `Provider.install_all`.

    None for a local, a parameter, a type parameter, or a symbol whose name is empty, none of
    which `deps` can be asked about. scip-python writes a module-level variable twice over,
    `STEPS.STEPS.`, and the repeat is dropped.
    """
    if symbol.startswith('local ') or symbol.count(' ') < 4:
        return None
    descriptors = parse_descriptors(symbol.split(' ', 4)[4])
    if not descriptors or descriptors[-1].suffix not in ('#', '.', '()') or not descriptors[-1].name:
        return None
    module = '.'.join(d.name for d in descriptors if d.suffix == '/')
    parts: list[Descriptor] = []
    for descriptor in descriptors:
        if descriptor.suffix not in ('#', '.', '()'):
            continue
        if not descriptor.name:
            return None
        if parts and descriptor.suffix == '.' and parts[-1].suffix == '.' and parts[-1].name == descriptor.name:
            continue
        parts.append(descriptor)
    last = parts[-1]
    if last.suffix == '#':
        kind = 'class'
    elif last.suffix == '()':
        kind = 'method' if len(parts) > 1 and parts[-2].suffix == '#' else 'function'
    else:
        kind = 'variable'
    return SymbolName(module, '.'.join(d.name for d in parts), kind)


# Raise whenever link_documents changes the rows it writes. A repo's fingerprint carries it,
# so the next index runs scip-python again over every repo, however unchanged its files are.
SCIP_LINK_VERSION = 1


@dataclass
class LinkedIndex:
    """One scip-python run as rows for the scip_* tables."""

    documents: list[dict] = field(default_factory=list)
    symbols: list[dict] = field(default_factory=list)
    references: list[dict] = field(default_factory=list)
    relationships: list[dict] = field(default_factory=list)


def split_lines(content: str) -> list[str]:
    """Lines as Python and Pyright count them. str.splitlines also breaks on a form feed, which neither does."""
    return re.split(r'\r\n|\r|\n', content)


def token_at(lines: list[str], occurrence: Occurrence) -> str:
    if occurrence.line != occurrence.end_line or occurrence.line >= len(lines):
        return ''
    return lines[occurrence.line][occurrence.column : occurrence.end_column]


def ast_position(lines: list[str], occurrence: Occurrence) -> tuple[int, int]:
    """An occurrence's start as `ast` counts it: a 1-based line and a UTF-8 byte column."""
    text = lines[occurrence.line] if occurrence.line < len(lines) else ''
    prefix = text[: occurrence.column]
    return occurrence.line + 1, len(prefix) if prefix.isascii() else len(prefix.encode())


def is_called(lines: list[str], occurrence: Occurrence) -> bool:
    """Whether the name is called where it stands: `(` follows it on its line."""
    return token_at(lines, occurrence) != '' and lines[occurrence.line][occurrence.end_column :].lstrip().startswith('(')


def is_on_receiver(lines: list[str], occurrence: Occurrence) -> bool:
    """Whether the name is read off a receiver, as `x.name` is: `.` precedes it on its line."""
    return token_at(lines, occurrence) != '' and lines[occurrence.line][: occurrence.column].rstrip().endswith('.')


def import_aliases(document: Document, lines: list[str]) -> dict[str, str]:
    """Each name a file imports under an alias, mapped to the symbol it stands for. scip-python spans `name as alias` whole."""
    aliases = {}
    for occurrence in document.occurrences:
        before, separator, alias = token_at(lines, occurrence).rpartition(' as ')
        if separator and before:
            aliases[alias.strip()] = occurrence.symbol
    return aliases


def link_documents(root: Path, repo: str, documents: list[Document], indexed: set[str]) -> LinkedIndex:
    """The files indy indexes, the symbols they define, and every value use of one of those symbols with its caller.

    A reference to a symbol no indexed file defines is dropped. That covers the standard
    library and third-party code, which `deps` reads from the syntactic rows, and the
    modules scip-python attributes to the project's own package by mistake.

    An occurrence stands only where the source spells its symbol's name, or an import alias
    of it. scip-python resolves a PEP 695 type parameter to the function or class declaring
    it, and writes a class's type parameter as a second definition of the class. Neither
    spells the name it claims.

    The caller is the scope ReferenceExtractor gives that position, so a SCIP caller and a
    syntactic one carry the same name, `STEPS['wslconfig']` included. A position inside an
    import, an annotation or a class base is no value use, unless something is called there
    or it sits inside a call in an annotation, as `Option(callback=f)` in `Annotated[...]` does.
    Nor is an assignment or `del`: scip-python writes every one after the first as a read.
    """
    linked = LinkedIndex()
    files = []
    for document in documents:
        path = root / document.relative_path
        file_path = compact_path(str(path))
        if file_path not in indexed:
            continue
        try:
            content = path.read_text(encoding='utf-8', errors='ignore')
        except OSError:
            continue
        files.append((file_path, document, content, split_lines(content)))
        linked.documents.append({'repo': repo, 'file_path': file_path})

    defined: dict[str, SymbolName] = {}
    for file_path, document, _, lines in files:
        for occurrence in document.occurrences:
            if not occurrence.roles & ROLE_DEFINITION or occurrence.symbol in defined:
                continue
            named = name_symbol(occurrence.symbol)
            if named is None or token_at(lines, occurrence) != named.member:
                continue
            defined[occurrence.symbol] = named
            linked.symbols.append(
                {
                    'repo': repo,
                    'symbol': occurrence.symbol,
                    'module': named.module,
                    'name': named.name,
                    'member': named.member,
                    'kind': named.kind,
                    'file_path': file_path,
                    'line': occurrence.line + 1,
                }
            )

    for file_path, document, content, lines in files:
        spans = extract_spans(file_path, content)
        aliases = import_aliases(document, lines)
        for occurrence in document.occurrences:
            named = defined.get(occurrence.symbol)
            if named is None or occurrence.roles & (ROLE_DEFINITION | ROLE_IMPORT | ROLE_WRITE):
                continue
            token = token_at(lines, occurrence)
            if token != named.member and aliases.get(token) != occurrence.symbol:
                continue
            position = ast_position(lines, occurrence)
            called = is_called(lines, occurrence)
            if not called and not spans.is_value(position):
                continue
            linked.references.append(
                {
                    'repo': repo,
                    'file_path': file_path,
                    'line': occurrence.line + 1,
                    'symbol': occurrence.symbol,
                    'member': named.member,
                    'source_symbol': spans.caller_at(position),
                    'ref_type': 'call' if called else 'reference',
                    'on_receiver': is_on_receiver(lines, occurrence),
                }
            )
        linked.relationships += [
            {'repo': repo, 'symbol': symbol, 'kind': kind, 'target_symbol': target}
            for symbol, kind, target in document.relationships
            if symbol in defined
        ]
    return linked


def venv_python(root: Path) -> Path | None:
    python = root / '.venv' / 'bin' / 'python'
    return python if python.exists() else None


def describe_environment(python: Path) -> str:
    """The --environment JSON for a venv: every installed distribution and its Python files."""
    result = subprocess.run([str(python), '-I', '-c', ENVIRONMENT_SCRIPT], capture_output=True, text=True, timeout=120)
    if result.returncode != 0:
        raise ScipError(f'listing the packages in {python.parent.parent} failed: {last_line(result.stderr)}')
    return result.stdout


def last_line(text: str) -> str:
    lines = [line for line in text.strip().splitlines() if line.strip()]
    return lines[-1] if lines else '(no output)'


def node_installed() -> bool:
    return all(shutil.which(program) for program in ('node', 'npm', 'npx'))


def lockfile_digest() -> str:
    """The pinned dependency tree, as a hash of the lockfile that names it."""
    return hashlib.sha256((LOCKFILE_DIR / 'package-lock.json').read_bytes()).hexdigest()


def install_scip_python() -> Path:
    """The directory scip-python is installed in from the lockfile, installing it on first use.

    One directory per lockfile, so a new lockfile installs beside the old one rather than over
    a copy another run may be using. It is built under a temporary name and renamed into place,
    so a directory at the final name is always a complete install. `--ignore-scripts`, because
    nothing in the tree needs an install script and none should run with access to the repos.
    """
    prefix = SCIP_PYTHON_DIR / lockfile_digest()[:16]
    if (prefix / 'node_modules' / '.bin' / 'scip-python').exists():
        return prefix
    SCIP_PYTHON_DIR.mkdir(parents=True, exist_ok=True)
    building = Path(tempfile.mkdtemp(prefix='.installing-', dir=SCIP_PYTHON_DIR))
    try:
        for name in LOCKFILES:
            shutil.copy(LOCKFILE_DIR / name, building / name)
        command = ['npm', 'ci', '--prefix', str(building), '--ignore-scripts', '--no-audit', '--no-fund']
        result = subprocess.run(command, capture_output=True, text=True, timeout=SCIP_PYTHON_TIMEOUT_SECONDS)
        if result.returncode != 0:
            raise ScipError(f'installing scip-python failed: {last_line(result.stderr or result.stdout)}')
        try:
            building.rename(prefix)
        except OSError:
            if not prefix.is_dir():
                raise
    finally:
        shutil.rmtree(building, ignore_errors=True)
    return prefix


def run_scip_python(root: Path, project_name: str, environment: str) -> list[Document]:
    """Index root with the pinned scip-python, from inside its venv, and decode what it wrote.

    The venv's bin leads PATH so the interpreter Pyright asks for search paths is the venv's,
    which is what resolves the project's own package to its source. `npx --no` runs the copy
    installed from the lockfile and never fetches one.
    """
    prefix = install_scip_python()
    venv_bin = root / '.venv' / 'bin'
    env = {**os.environ, 'PATH': f'{venv_bin}{os.pathsep}{os.environ.get("PATH", "")}', 'VIRTUAL_ENV': str(venv_bin.parent)}
    with tempfile.TemporaryDirectory(prefix='indy-scip-') as scratch:
        environment_file = Path(scratch) / 'environment.json'
        environment_file.write_text(environment)
        output = Path(scratch) / 'index.scip'
        command = [
            'npx',
            '--prefix',
            str(prefix),
            '--no',
            '--',
            'scip-python',
            'index',
            '--quiet',
            '--cwd',
            str(root),
            '--project-name',
            project_name,
            '--project-version',
            PROJECT_VERSION,
            '--environment',
            str(environment_file),
            '--output',
            str(output),
        ]
        try:
            result = subprocess.run(command, capture_output=True, text=True, env=env, timeout=SCIP_PYTHON_TIMEOUT_SECONDS)
        except FileNotFoundError as exc:
            raise ScipError('npx is not on PATH') from exc
        except subprocess.TimeoutExpired as exc:
            raise ScipError(f'scip-python ran past {SCIP_PYTHON_TIMEOUT_SECONDS}s') from exc
        if result.returncode != 0:
            raise ScipError(f'scip-python exited {result.returncode}: {last_line(result.stderr or result.stdout)}')
        if not output.exists() or output.stat().st_size == 0:
            raise ScipError(f'scip-python wrote an empty index: {last_line(result.stderr or result.stdout)}')
        return decode_index(output.read_bytes())


def environment_digest(environment: str) -> str:
    """The environment with its order normalized, so the same packages always hash the same."""
    return json.dumps(sorted(json.loads(environment), key=lambda dist: dist['name']), sort_keys=True)
